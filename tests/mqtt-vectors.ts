// Encodes MQTT requests with the PocketJS SDK (framework/src/io/mqtt.ts) and
// writes them as a C header, so tests/mqtt-record.c parses exactly the bytes
// a worker submits.
//   bun tests/mqtt-vectors.ts <output.h>
import { writeFileSync } from "node:fs";
import {
  encodeMqttDisconnect, encodeMqttOpen, encodeMqttPublish, encodeMqttSubscribe, encodeMqttUnsubscribe,
} from "../third_party/pocketjs/framework/src/io/mqtt.ts";

const vectors: Record<string, Uint8Array> = {
  open_v311: encodeMqttOpen({
    url: "mqtts://broker.local:8883", clientId: "tab5", username: "user", password: "secret",
    keepAliveSeconds: 30, reconnectMs: 2000, timeoutMs: 8000, maxMessageBytes: 4096, cleanStart: false,
    will: { topic: "tab5/status", payload: "offline", qos: 1, retain: true },
    tls: { ca: "CA", certificate: "CERT", key: "KEY", keyPassword: "pw", commonName: "broker", alpn: ["mqtt", "x-amzn-mqtt-ca"] },
  }).descriptor,
  open_v5: encodeMqttOpen({
    url: "ws://b/mqtt", protocol: "5", clientId: null, sessionExpirySeconds: 3600, receiveMaximum: 16,
    maximumPacketSize: 65536, topicAliasMaximum: 8, requestResponseInformation: true,
    userProperties: [["a", "1"], ["a", "2"]],
    will: { topic: "w", payload: Uint8Array.of(0, 1, 2), payloadUtf8: false, delaySeconds: 5, messageExpirySeconds: 60,
      contentType: "application/octet-stream", responseTopic: "r/1", correlationData: Uint8Array.of(9, 8), userProperties: { k: "v" } },
  }).descriptor,
  open_plain: encodeMqttOpen({ url: "mqtt://192.168.1.10" }).descriptor,
  publish_inline: encodeMqttPublish("t/1", "hi", { qos: 2, retain: true }, false).request,
  publish_staged: encodeMqttPublish("t/big", new Uint8Array(5000), { qos: 1 }, false).request,
  publish_v5: encodeMqttPublish("t", "x", {
    payloadUtf8: true, messageExpirySeconds: 10, contentType: "text/plain", responseTopic: "reply/1",
    correlationData: "id-7", topicAlias: 3, userProperties: [["k", "v"], ["k", "w"]],
  }, true).request,
  publish_empty: encodeMqttPublish("t/e", undefined, {}, false).request,
  subscribe_v5: encodeMqttSubscribe(["a/+/c", { filter: "d/#", qos: 1 }, { filter: "$share/g/e", qos: 2 }],
    { noLocal: true, retainAsPublished: true, retainHandling: 2, subscriptionIdentifier: 7, userProperties: { u: "1" } }, true).request,
  subscribe_v311: encodeMqttSubscribe("#", {}, false).request,
  unsubscribe: encodeMqttUnsubscribe(["a", "b/#"], {}, false).request,
  disconnect_v5: encodeMqttDisconnect({ reasonCode: 4, sessionExpirySeconds: 120, userProperties: { why: "bye" } }, true),
  disconnect_zero: encodeMqttDisconnect({ sessionExpirySeconds: 0 }, true),
};

let header = "/* Generated by tests/mqtt-vectors.ts from the PocketJS SDK encoders. */\n#include <stdint.h>\n";
for (const [name, bytes] of Object.entries(vectors)) {
  header += `static const uint8_t ${name}[] = {${Array.from(bytes).join(",")}};\n`;
}
const output = process.argv[2];
if (!output) throw new Error("usage: bun tests/mqtt-vectors.ts <output.h>");
writeFileSync(output, header);
